'use strict';
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PICKLEQUEUE_PLAYWRIGHT_PATH || 'playwright-core');
const url = process.argv[2] || 'http://127.0.0.1:8080';
const screenshots = process.env.PICKLEQUEUE_SCREENSHOTS;

(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(url);
    await page.getByRole('button',{name:'+ New session',exact:true}).click();
    await page.getByLabel('Session name',{exact:true}).fill('Browser QA (synthetic)');
    await page.getByRole('button',{name:'Create session',exact:true}).click();
    await page.getByRole('button',{name:'Load demo roster',exact:true}).click();
    await page.getByRole('button',{name:'Attendance',exact:false}).first().click();
    await page.locator('.attendance-table').waitFor();
    for(let i=0;i<12;i++)await page.getByRole('button',{name:'Check in',exact:true}).first().click();
    await page.getByRole('button',{name:'Live queue',exact:false}).click();
    await page.getByRole('button',{name:'Fill open courts'}).click();
    await page.getByRole('button',{name:'Start game',exact:true}).first().waitFor();
    assert.equal(await page.getByRole('button',{name:'Start game',exact:true}).count(),2);
    const id = new URLSearchParams(new URL(page.url()).hash.slice(1)).get('session');
    let state = await (await page.request.get(`${url}/api/sessions/${id}`)).json();
    assert.equal(state.metrics.on_court,8);
    assert.equal(state.metrics.waiting,4);
    for(const game of state.games)assert.ok(game.expected_a>=.4&&game.expected_a<=.6);
    await page.getByRole('button',{name:'Start game',exact:true}).first().click();
    await page.getByRole('button',{name:'Record result',exact:true}).click();
    await page.getByLabel('Team A score').fill('11');
    await page.getByLabel('Team B score').fill('11');
    await page.getByRole('button',{name:'Save result',exact:true}).click();
    await page.locator('#result-dialog .form-error').filter({hasText:'needs a winner'}).waitFor();
    await page.getByLabel('Team B score').fill('8');
    await page.getByRole('button',{name:'Save result',exact:true}).click();
    await page.locator('#result-dialog').waitFor({state:'hidden'});
    state = await (await page.request.get(`${url}/api/sessions/${id}`)).json();
    assert.equal(state.metrics.completed_games,1);
    assert.equal(state.metrics.waiting,8);
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.getByLabel('Reason',{exact:true}).fill('Synthetic cancellation');
    await page.getByRole('button',{name:'Cancel game',exact:true}).click();
    await page.locator('#confirm-dialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Fill open courts'}).click();
    await page.getByRole('button',{name:'Attendance',exact:false}).first().click();
    await page.locator('.attendance-table').waitFor();
    await page.getByLabel('Search players').fill('Zion');
    assert.equal(await page.locator('tr[data-name]:visible').count(),1);
    await page.getByRole('button',{name:'Game results',exact:false}).first().click();
    await page.goBack();
    await page.locator('.attendance-table').waitFor();
    assert.equal(new URLSearchParams(new URL(page.url()).hash.slice(1)).get('view'),'attendance');
    await page.goForward();
    await page.locator('.result-table').waitFor();
    await page.reload();
    await page.locator('.result-table').waitFor();
    await page.getByRole('button',{name:'Live queue',exact:false}).click();
    await page.locator('.courts').waitFor();
    await page.locator('#view-content').evaluate(node=>Promise.all(node.getAnimations().map(a=>a.finished)));
    if(screenshots)await page.screenshot({path:`${screenshots}/desktop.png`,fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.getByLabel('Choose session').selectOption('new');
    await page.locator('#create-dialog').waitFor({state:'visible'});
    await page.keyboard.press('Escape');
    const mobileContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    const mobile=await mobileContext.newPage();
    mobile.on('pageerror',error=>errors.push(error.message));
    await mobile.goto(`${url}/#session=${id}&view=queue`);
    await mobile.locator('.courts').waitFor();
    assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    assert.ok(await mobile.getByRole('button',{name:'Fill open courts'}).evaluate(node=>node.getBoundingClientRect().height>=44));
    await mobile.getByLabel('Choose session').selectOption('new');
    await mobile.locator('#create-dialog').waitFor({state:'visible'});
    await mobile.locator('#create-dialog').getByRole('button',{name:'Cancel',exact:true}).click();
    if(screenshots)await mobile.screenshot({path:`${screenshots}/mobile.png`,fullPage:true});
    await mobileContext.close();
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.getByRole('button',{name:'Game results',exact:false}).first().click();
    await page.locator('.result-table').waitFor();
    assert.equal(await page.locator('#view-content').evaluate(node=>getComputedStyle(node).animationName),'none');
    assert.ok(await page.locator('#view-content').isVisible());
    await page.getByRole('button',{name:'Import roster',exact:true}).click();
    await page.keyboard.press('Escape');
    assert.ok(await page.getByRole('button',{name:'Import roster',exact:true}).evaluate(node=>node===document.activeElement));
    await page.setViewportSize({width:1440,height:1000});
    await page.getByRole('button',{name:'Live queue',exact:false}).click();
    await page.locator('.courts').waitFor();
    while(await page.getByRole('button',{name:'Cancel',exact:true}).count()) {
      await page.getByRole('button',{name:'Cancel',exact:true}).first().click();
      await page.getByLabel('Reason',{exact:true}).fill('Closing synthetic session');
      await page.getByRole('button',{name:'Cancel game',exact:true}).click();
      await page.locator('#confirm-dialog').waitFor({state:'hidden'});
    }
    await page.getByRole('button',{name:'Close session & finalize ratings',exact:true}).click();
    await page.getByRole('button',{name:'Close & finalize',exact:true}).click();
    await page.locator('#confirm-dialog').waitFor({state:'hidden'});
    assert.ok(await page.getByRole('button',{name:'Fill open courts'}).isDisabled());
    state = await (await page.request.get(`${url}/api/sessions/${id}`)).json();
    assert.equal(state.session.status,'closed');
    assert.equal(state.players.reduce((n,p)=>n+p.rated_games,0),4);
    await page.getByRole('button',{name:'+ New session',exact:true}).click();
    await page.getByLabel('Session name',{exact:true}).fill('CSV QA (synthetic)');
    await page.getByRole('button',{name:'Create session',exact:true}).click();
    await page.getByRole('button',{name:'Import roster',exact:true}).click();
    await page.getByLabel('Source',{exact:true}).selectOption('manual');
    await page.getByLabel('Club identifier').fill(`csv-qa-${Date.now()}`);
    await page.getByLabel('Or paste CSV').fill('external_id,name,rsvp,membership,waiver,initial_rating\nqa-1,"<img src=x onerror=window.injected=true>",yes,active,unknown,1200');
    await page.locator('#import-dialog').getByRole('button',{name:'Import roster',exact:true}).click();
    await page.locator('#import-dialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Attendance',exact:false}).first().click();
    await page.locator('.attendance-table').waitFor();
    assert.ok(await page.getByText('<img src=x onerror=window.injected=true>',{exact:true}).isVisible());
    assert.equal(await page.evaluate(()=>window.injected),undefined);
    await page.getByRole('button',{name:'Check in',exact:true}).click();
    await page.getByText('Not eligible',{exact:true}).waitFor();
    const csvId=new URLSearchParams(new URL(page.url()).hash.slice(1)).get('session');
    const csvState=await(await page.request.get(`${url}/api/sessions/${csvId}`)).json();
    assert.equal(csvState.metrics.waiting,0);
    assert.equal(csvState.metrics.present,1);
    assert.deepEqual(errors,[]);
    console.log('PASS: browser session creation, demo, check-ins, two balanced courts, result validation, cancellation, search, history navigation, reload, mobile/touch targets, reduced motion, dialog keyboard focus, rating finalization, CSV import, unverified eligibility, and HTML injection escaping.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
